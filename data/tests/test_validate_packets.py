from __future__ import annotations

import hashlib
import tempfile
import unittest
from pathlib import Path

from tools.validate_packets import validate_packet, validate_repository


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _manifest(file_hash: str, path: str = "observations/points.csv") -> str:
    return f'''schema_version = 1
packet_id = "example-packet"
packet_version = "1"
title = "Example packet"
description = "A test-only scientific packet."
license_or_use_basis = "Test fixture generated by this repository."

[[sources]]
source_id = "fixture"
citation = "Generated test fixture"
use_basis = "Repository contract test"

[[domains]]
domain_id = "fixture-domain"
description = "Synthetic values used only by the validator tests."

[[files]]
path = "{path}"
role = "observations"
media_type = "text/csv"
sha256 = "{file_hash}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "All columns are dimensionless."
'''


class PacketValidationTests(unittest.TestCase):
    def make_packet(self) -> tuple[tempfile.TemporaryDirectory[str], Path, Path]:
        temporary = tempfile.TemporaryDirectory()
        root = Path(temporary.name) / "packets" / "example-packet" / "1"
        observations = root / "observations"
        observations.mkdir(parents=True)
        payload = b"point,value\n1,0.5\n"
        data = observations / "points.csv"
        data.write_bytes(payload)
        manifest = root / "packet.toml"
        manifest.write_text(_manifest(_sha256(payload)), encoding="utf-8")
        return temporary, manifest, data

    def test_valid_packet_passes(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        self.assertEqual(validate_packet(manifest), [])

    def test_hash_mismatch_fails(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        data.write_bytes(b"changed\n")
        self.assertTrue(
            any("hash mismatch" in error for error in validate_packet(manifest))
        )

    def test_unsafe_path_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(_manifest("0" * 64, "../outside.csv"), encoding="utf-8")
        self.assertTrue(
            any("unsafe path" in error for error in validate_packet(manifest))
        )

    def test_unlisted_file_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        extra = manifest.parent / "provenance" / "note.txt"
        extra.parent.mkdir()
        extra.write_text("unlisted", encoding="utf-8")
        self.assertTrue(
            any("unlisted files" in error for error in validate_packet(manifest))
        )

    def test_symlinked_content_fails(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        target = manifest.parent / "outside.csv"
        target.write_bytes(data.read_bytes())
        data.unlink()
        data.symlink_to(target)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_symlinked_manifest_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        real_manifest = manifest.with_name("real-packet.toml")
        manifest.rename(real_manifest)
        manifest.symlink_to(real_manifest)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_unlisted_symlinked_directory_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        external = Path(temporary.name) / "external"
        external.mkdir()
        (manifest.parent / "provenance").symlink_to(external, target_is_directory=True)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_malformed_toml_field_types_return_errors(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(_manifest("0" * 64, "."), encoding="utf-8")
        self.assertTrue(validate_packet(manifest))

        temporary_two, manifest_two, _ = self.make_packet()
        self.addCleanup(temporary_two.cleanup)
        text = manifest_two.read_text(encoding="utf-8").replace(
            'source_refs = ["fixture"]',
            'source_refs = [{ invalid = "table" }]',
        )
        manifest_two.write_text(text, encoding="utf-8")
        self.assertTrue(validate_packet(manifest_two))

    def test_empty_placeholder_directory_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        (manifest.parent / "parameters").mkdir()
        root = Path(temporary.name)
        self.assertTrue(
            any("empty directory" in error for error in validate_repository(root))
        )

    def test_unmanifested_empty_packet_tree_fails(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "packets" / "example-packet" / "1" / "parameters").mkdir(
                parents=True
            )
            self.assertTrue(
                any(
                    "missing packet.toml" in error
                    for error in validate_repository(root)
                )
            )

    def test_empty_packet_id_directory_fails(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "packets" / "example-packet").mkdir(parents=True)
            self.assertTrue(
                any(
                    "empty packet directory" in error
                    for error in validate_repository(root)
                )
            )


if __name__ == "__main__":
    unittest.main()
