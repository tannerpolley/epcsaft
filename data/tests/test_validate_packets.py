from __future__ import annotations

import hashlib
import tempfile
import unittest
from pathlib import Path

from tools.validate_packets import (
    packet_fingerprint,
    validate_packet,
    validate_repository,
)


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _manifest(file_hash: str, path: str = "observations/points.csv") -> str:
    return f'''schema_version = 2
packet_id = "example-packet"
packet_version = "1"
title = "Example packet"
description = "A test-only scientific packet."
license_or_use_basis = "Test fixture generated by this repository."
tolerance_rationale = "Synthetic fixture; no scientific tolerance is claimed."

[[sources]]
source_id = "fixture"
citation = "Generated test fixture"
use_basis = "Repository contract test"

[[domains]]
domain_id = "fixture-domain"
description = "Synthetic values used only by the validator tests."

[[files]]
path = "{path}"
role = "observations"
media_type = "text/csv"
sha256 = "{file_hash}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "All columns are dimensionless."
'''


class PacketValidationTests(unittest.TestCase):
    def make_packet(self) -> tuple[tempfile.TemporaryDirectory[str], Path, Path]:
        temporary = tempfile.TemporaryDirectory()
        root = Path(temporary.name) / "packets" / "example-packet" / "1"
        observations = root / "observations"
        observations.mkdir(parents=True)
        payload = b"point,value\n1,0.5\n"
        data = observations / "points.csv"
        data.write_bytes(payload)
        manifest = root / "packet.toml"
        manifest.write_text(_manifest(_sha256(payload)), encoding="utf-8")
        return temporary, manifest, data

    def make_parameter_bundle_packet(
        self,
    ) -> tuple[tempfile.TemporaryDirectory[str], Path, Path]:
        temporary, manifest, _ = self.make_packet()
        parameters = manifest.parent / "parameters"
        parameters.mkdir()
        component_payload = b"component_id,name\nwater,Water\n"
        (parameters / "components.csv").write_bytes(component_payload)
        bundle_payload = b'''schema_version = 1
bundle_id = "example-bundle"
bundle_version = 1
purpose = "user-provided"
files = ["components.csv"]
'''
        bundle = parameters / "bundle.toml"
        bundle.write_bytes(bundle_payload)
        manifest.write_text(
            manifest.read_text(encoding="utf-8")
            + f'''\n[[files]]
path = "parameters/bundle.toml"
role = "parameters"
media_type = "application/toml"
sha256 = "{_sha256(bundle_payload)}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "Bundle metadata are non-numeric identifiers."

[[files]]
path = "parameters/components.csv"
role = "parameters"
media_type = "text/csv"
sha256 = "{_sha256(component_payload)}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "Identity metadata are non-numeric."
''',
            encoding="utf-8",
        )
        return temporary, manifest, bundle

    def test_valid_packet_passes(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        self.assertEqual(validate_packet(manifest), [])

    def test_tolerance_rationale_is_required(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(
            manifest.read_text(encoding="utf-8").replace(
                'tolerance_rationale = "Synthetic fixture; no scientific tolerance is claimed."\n',
                "",
            ),
            encoding="utf-8",
        )
        self.assertTrue(
            any("tolerance_rationale is required" in error for error in validate_packet(manifest))
        )

    def test_schema_version_one_is_reserved_for_historical_packets(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(
            manifest.read_text(encoding="utf-8").replace("schema_version = 2", "schema_version = 1"),
            encoding="utf-8",
        )
        self.assertTrue(
            any(
                "schema_version 1 is reserved for accepted historical packets" in error
                for error in validate_packet(manifest)
            )
        )

    def test_packet_fingerprint_is_stable_and_content_bound(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        first = packet_fingerprint(manifest.parent)
        self.assertEqual(first, packet_fingerprint(manifest.parent))
        data.write_bytes(b"changed\n")
        self.assertNotEqual(first, packet_fingerprint(manifest.parent))

    def test_packet_fingerprint_uses_unambiguous_length_framing(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            one = root / "one"
            two = root / "two"
            one.mkdir()
            two.mkdir()
            (one / "a").write_bytes(b"x\x00b\x00y")
            (two / "a").write_bytes(b"x")
            (two / "b").write_bytes(b"y")
            self.assertNotEqual(packet_fingerprint(one), packet_fingerprint(two))

    def test_hash_mismatch_fails(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        data.write_bytes(b"changed\n")
        self.assertTrue(
            any("hash mismatch" in error for error in validate_packet(manifest))
        )

    def test_provenance_kind_is_required_and_supported(self) -> None:
        for payload in (b"schema_version = 1\n", b'provenance_kind = "unknown-v1"\n'):
            with self.subTest(payload=payload):
                temporary, manifest, _ = self.make_packet()
                self.addCleanup(temporary.cleanup)
                provenance = manifest.parent / "provenance" / "origin.toml"
                provenance.parent.mkdir()
                provenance.write_bytes(payload)
                manifest.write_text(
                    manifest.read_text(encoding="utf-8")
                    + f'''\n[[files]]
path = "provenance/origin.toml"
role = "provenance"
media_type = "application/toml"
sha256 = "{_sha256(payload)}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "Repository metadata are non-numeric identifiers."
''',
                    encoding="utf-8",
                )
                self.assertTrue(
                    any(
                        "unsupported provenance_kind" in error
                        for error in validate_packet(manifest)
                    )
                )

    def test_source_record_provenance_supports_mixed_origins(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        payload = f'''schema_version = 1
provenance_kind = "source-record-provenance-v1"

[[records]]
retained_path = "observations/points.csv"
origin_repository = "example/source-a"
origin_commit = "{"a" * 40}"
origin_tree = "{"b" * 40}"
origin_path = "data/points.csv"
sha256 = "{_sha256(data.read_bytes())}"
'''.encode()
        provenance = manifest.parent / "provenance" / "source-origin.toml"
        provenance.parent.mkdir()
        provenance.write_bytes(payload)
        manifest.write_text(
            manifest.read_text(encoding="utf-8")
            + f'''
[[files]]
path = "provenance/source-origin.toml"
role = "provenance"
media_type = "application/toml"
sha256 = "{_sha256(payload)}"
source_refs = ["fixture"]
domain_refs = ["fixture-domain"]
units_basis = "Source origin metadata are non-numeric identifiers."
''',
            encoding="utf-8",
        )
        self.assertEqual(validate_packet(manifest), [])

    def test_parameter_bundle_file_set_is_exact(self) -> None:
        temporary, manifest, bundle = self.make_parameter_bundle_packet()
        self.addCleanup(temporary.cleanup)
        self.assertEqual(validate_packet(manifest), [])

        original = bundle.read_bytes()
        changed = original.replace(b'"components.csv"', b'"missing.csv"')
        bundle.write_bytes(changed)
        manifest.write_text(
            manifest.read_text(encoding="utf-8").replace(
                _sha256(original), _sha256(changed)
            ),
            encoding="utf-8",
        )
        self.assertTrue(
            any(
                "parameter bundle file set is incomplete" in error
                for error in validate_packet(manifest)
            )
        )

    def test_unsafe_path_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(_manifest("0" * 64, "../outside.csv"), encoding="utf-8")
        self.assertTrue(
            any("unsafe path" in error for error in validate_packet(manifest))
        )

    def test_unlisted_file_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        extra = manifest.parent / "provenance" / "note.txt"
        extra.parent.mkdir()
        extra.write_text("unlisted", encoding="utf-8")
        self.assertTrue(
            any("unlisted files" in error for error in validate_packet(manifest))
        )

    def test_symlinked_content_fails(self) -> None:
        temporary, manifest, data = self.make_packet()
        self.addCleanup(temporary.cleanup)
        target = manifest.parent / "outside.csv"
        target.write_bytes(data.read_bytes())
        data.unlink()
        data.symlink_to(target)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_symlinked_manifest_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        real_manifest = manifest.with_name("real-packet.toml")
        manifest.rename(real_manifest)
        manifest.symlink_to(real_manifest)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_unlisted_symlinked_directory_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        external = Path(temporary.name) / "external"
        external.mkdir()
        (manifest.parent / "provenance").symlink_to(external, target_is_directory=True)
        self.assertTrue(
            any("symlink" in error for error in validate_packet(manifest))
        )

    def test_malformed_toml_field_types_return_errors(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        manifest.write_text(_manifest("0" * 64, "."), encoding="utf-8")
        self.assertTrue(validate_packet(manifest))

        temporary_two, manifest_two, _ = self.make_packet()
        self.addCleanup(temporary_two.cleanup)
        text = manifest_two.read_text(encoding="utf-8").replace(
            'source_refs = ["fixture"]',
            'source_refs = [{ invalid = "table" }]',
        )
        manifest_two.write_text(text, encoding="utf-8")
        self.assertTrue(validate_packet(manifest_two))

    def test_empty_placeholder_directory_fails(self) -> None:
        temporary, manifest, _ = self.make_packet()
        self.addCleanup(temporary.cleanup)
        (manifest.parent / "parameters").mkdir()
        root = Path(temporary.name)
        self.assertTrue(
            any("empty directory" in error for error in validate_repository(root))
        )

    def test_unmanifested_empty_packet_tree_fails(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "packets" / "example-packet" / "1" / "parameters").mkdir(
                parents=True
            )
            self.assertTrue(
                any(
                    "missing packet.toml" in error
                    for error in validate_repository(root)
                )
            )

    def test_empty_packet_id_directory_fails(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "packets" / "example-packet").mkdir(parents=True)
            self.assertTrue(
                any(
                    "empty packet directory" in error
                    for error in validate_repository(root)
                )
            )


if __name__ == "__main__":
    unittest.main()
