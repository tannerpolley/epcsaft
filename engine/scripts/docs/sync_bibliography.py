"""Generate the project bibliography from cited records in the Zotero export.

Zotero owns bibliographic metadata. This writes the project-only snapshot; never
hand-edit the target. Entries are copied verbatim apart from dropped local-path
fields, so the export stays the single source of truth.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = Path.home() / "Zotero/exports/references.bib"
TARGET = ROOT / "engine/docs/latex/references.bib"
KEYS_FILE = ROOT / "engine/docs/latex/cited_keys.txt"
DROP_FIELDS = ("file", "abstract", "urldate", "keywords", "annotation")

ENTRY = re.compile(r"^@(\w+)\s*\{\s*([^,\s]+)\s*,", re.M)


def cited_keys() -> list[str]:
    lines = KEYS_FILE.read_text(encoding="utf-8").splitlines()
    return [s for line in lines if (s := line.strip()) and not s.startswith("#")]


def entries(text: str) -> dict[str, str]:
    """Map citation key -> raw entry text, using brace matching."""
    found: dict[str, str] = {}
    for match in ENTRY.finditer(text):
        depth, index = 0, text.index("{", match.start())
        for position in range(index, len(text)):
            if text[position] == "{":
                depth += 1
            elif text[position] == "}":
                depth -= 1
                if depth == 0:
                    found[match.group(2)] = text[match.start() : position + 1]
                    break
    return found


def strip_fields(entry: str) -> str:
    kept = [
        line
        for line in entry.splitlines()
        if not re.match(rf"\s*({'|'.join(DROP_FIELDS)})\s*=", line, re.I)
    ]
    return "\n".join(kept)


def generated() -> str:
    if not SOURCE.is_file() or SOURCE.is_symlink() or SOURCE.stat().st_size == 0:
        raise SystemExit(f"canonical Better BibTeX export is unavailable: {SOURCE}")
    available = entries(SOURCE.read_text(encoding="utf-8"))
    wanted = cited_keys()
    missing = [key for key in wanted if key not in available]
    if missing:
        raise SystemExit(
            "cited keys missing from the canonical export "
            f"(set the Zotero citation key or add the item): {', '.join(missing)}"
        )
    body = "\n\n".join(strip_fields(available[key]) for key in wanted) + "\n"
    if "file =" in body.casefold() or str(Path.home()) in body:
        raise SystemExit("generated bibliography contains a local attachment path")
    header = (
        "% Generated by engine/scripts/docs/sync_bibliography.py from the canonical\n"
        "% Zotero Better BibTeX export. Do not hand-edit; edit Zotero and re-run.\n\n"
    )
    return header + body


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the snapshot is stale")
    args = parser.parse_args()

    expected = generated()
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
    count = len(cited_keys())

    if current == expected:
        print(f"Project bibliography is current ({len(expected)} bytes, {count} records).")
        return
    if args.check:
        raise SystemExit(f"project bibliography is stale; run {Path(__file__).name}")

    descriptor, name = tempfile.mkstemp(prefix=".references.bib.", dir=TARGET.parent)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(expected)
        temporary.chmod(0o644)
        temporary.replace(TARGET)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Generated project bibliography ({len(expected)} bytes, {count} records).", file=sys.stderr)


if __name__ == "__main__":
    main()
